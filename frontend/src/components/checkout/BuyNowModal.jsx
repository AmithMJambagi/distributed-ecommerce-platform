import React, { useState, useEffect } from 'react';
import { X, ExternalLink } from 'lucide-react';
import { useNavigate } from 'react-router-dom';
import { useAuth } from '../../context/AuthContext';
import { userApi } from '../../api/userApi';
import { orderApi } from '../../api/orderApi';
import { paymentApi } from '../../api/paymentApi';
import { formatCurrency, PLACEHOLDER_IMAGE } from '../../utils/formatters';
import LoadingSpinner from '../common/LoadingSpinner';
import Alert from '../common/Alert';

export default function BuyNowModal({ product, isOpen, onClose }) {
  const { user, isAuthenticated, openAuthModal } = useAuth();
  const navigate = useNavigate();

  const [quantity, setQuantity] = useState(1);
  const [address, setAddress] = useState('');
  const [loading, setLoading] = useState(false);
  const [statusMessage, setStatusMessage] = useState('');
  const [error, setError] = useState('');

  // If unauthenticated, close and prompt auth modal
  useEffect(() => {
    if (isOpen && !isAuthenticated) {
      onClose();
      openAuthModal('email');
    }
  }, [isOpen, isAuthenticated, onClose, openAuthModal]);

  // Pre-fill address from user profile
  useEffect(() => {
    if (isOpen && isAuthenticated) {
      userApi
        .getProfile()
        .then((profile) => {
          if (profile && profile.address) {
            setAddress(profile.address);
          }
        })
        .catch((err) => {
          console.warn('Could not load user profile for address pre-fill', err);
        });
    }
  }, [isOpen, isAuthenticated]);

  if (!isOpen || !product || !isAuthenticated) return null;

  const maxAllowed = Math.min(10, Math.max(1, Number(product.availableStock ?? 10)));
  const total = Number(product.price || 0) * quantity;

  const handleProceedToPayment = async (e) => {
    e.preventDefault();
    if (!isAuthenticated) {
      onClose();
      openAuthModal('email');
      return;
    }

    if (!address.trim()) {
      setError('Please provide a complete shipping address.');
      return;
    }

    setError('');
    setLoading(true);
    setStatusMessage('Reserving stock and initiating order...');

    try {
      // 1. Create instant order via Gateway
      const order = await orderApi.buyNow(product.id, quantity, address);

      // 2. Fetch active Razorpay payment link generated by Saga in Payment Service
      setStatusMessage('Fetching secure Razorpay payment link...');
      const paymentDetails = await paymentApi.pollPaymentLink(order.orderId);

      if (paymentDetails && paymentDetails.paymentUrl) {
        setStatusMessage('Redirecting to Razorpay payment gateway...');
        window.location.href = paymentDetails.paymentUrl;
      } else {
        throw new Error('Payment link not received. Please try again.');
      }
    } catch (err) {
      console.error('Buy Now checkout error:', err);
      setError(
        err.response?.data?.message ||
          err.message ||
          'Could not process order. Inventory may be temporarily reserved.'
      );
      setLoading(false);
      setStatusMessage('');
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/40 backdrop-blur-none animate-in fade-in duration-150">
      <div className="bg-white w-full max-w-lg border border-neutral-900 shadow-2xl relative">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-neutral-200">
          <h2 className="font-black text-sm tracking-widest uppercase text-black">
            Buy Now
          </h2>
          <button
            onClick={onClose}
            disabled={loading}
            className="p-1 text-neutral-400 hover:text-black border border-transparent hover:border-black transition-colors disabled:opacity-50"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Form Body */}
        <form onSubmit={handleProceedToPayment} className="p-6 space-y-5">
          {error && <Alert type="error" message={error} onClose={() => setError('')} />}

          {/* Product Summary */}
          <div className="flex gap-4 p-4 border border-neutral-200 bg-neutral-50/50">
            <img
              src={product.primaryImageUrl || PLACEHOLDER_IMAGE}
              alt={product.name}
              onError={(e) => {
                e.currentTarget.src = PLACEHOLDER_IMAGE;
              }}
              className="w-16 h-16 object-contain bg-white border border-neutral-200 p-1 shrink-0"
            />
            <div className="flex-1 min-w-0">
              <h3 className="text-xs font-bold uppercase tracking-tight text-neutral-900 truncate">
                {product.name}
              </h3>
              <p className="text-xs font-mono text-neutral-500 mt-1">
                Unit: {formatCurrency(product.price)}
              </p>
              <div className="mt-3 flex items-center gap-2">
                <span className="text-[11px] font-bold uppercase text-neutral-600">Quantity:</span>
                <div className="flex items-center border border-neutral-300 bg-white">
                  <button
                    type="button"
                    disabled={loading}
                    onClick={() => setQuantity((q) => Math.max(1, q - 1))}
                    className="px-2 py-0.5 text-xs text-neutral-700 hover:bg-neutral-100 disabled:opacity-30"
                  >
                    -
                  </button>
                  <span className="px-3 py-0.5 text-xs font-mono font-bold text-neutral-900 border-x border-neutral-300">
                    {quantity}
                  </span>
                  <button
                    type="button"
                    disabled={loading || quantity >= maxAllowed}
                    onClick={() => setQuantity((q) => Math.min(maxAllowed, q + 1))}
                    className="px-2 py-0.5 text-xs text-neutral-700 hover:bg-neutral-100 disabled:opacity-30 disabled:cursor-not-allowed"
                  >
                    +
                  </button>
                </div>
                {quantity >= maxAllowed && (
                  <span className="text-[10px] font-mono text-neutral-500">
                    {Number(product.availableStock) < 10
                      ? `(Max: ${product.availableStock} in stock)`
                      : '(Max: 10 per order)'}
                  </span>
                )}
              </div>
            </div>
          </div>

          {/* Shipping Address */}
          <div>
            <label className="block text-[11px] font-bold text-neutral-700 uppercase tracking-wider mb-1">
              Delivery Address
            </label>
            <textarea
              required
              disabled={loading}
              rows={3}
              value={address}
              onChange={(e) => setAddress(e.target.value)}
              placeholder="Street address, City, State, PIN Code"
              className="w-full px-3 py-2 text-xs border border-neutral-300 focus:border-black focus:outline-none transition font-sans disabled:bg-neutral-50"
            />
          </div>

          {/* Price Breakdown */}
          <div className="border border-neutral-200 p-4 space-y-1.5 text-xs">
            <div className="flex justify-between text-neutral-500">
              <span className="uppercase tracking-wider text-[11px]">Subtotal ({quantity} item{quantity > 1 ? 's' : ''})</span>
              <span className="font-mono text-neutral-900">{formatCurrency(total)}</span>
            </div>
            <div className="flex justify-between text-neutral-500">
              <span className="uppercase tracking-wider text-[11px]">Express Shipping</span>
              <span className="font-mono text-black font-semibold">FREE</span>
            </div>
            <div className="border-t border-neutral-200 pt-2 flex justify-between font-bold text-sm">
              <span className="uppercase tracking-wider">Total Payable</span>
              <span className="text-black font-mono font-black">{formatCurrency(total)}</span>
            </div>
          </div>

          {/* Action Button */}
          <button
            type="submit"
            disabled={loading}
            className="w-full py-3.5 px-4 bg-black hover:bg-neutral-800 disabled:bg-neutral-300 text-white font-bold text-xs uppercase tracking-wider transition flex items-center justify-center gap-2"
          >
            {loading ? (
              <div className="flex items-center gap-2">
                <LoadingSpinner size="sm" color="white" />
                <span>{statusMessage || 'Processing Payment...'}</span>
              </div>
            ) : (
              <>
                <span>Pay {formatCurrency(total)} via Razorpay</span>
                <ExternalLink className="w-3.5 h-3.5" />
              </>
            )}
          </button>
        </form>
      </div>
    </div>
  );
}
